        if ~isfolder(reportsDir)
            mkdir(reportsDir);
        end
        outHtmlPath = fullfile(reportsDir, sprintf('report_%s.html', reportData.patientId));
    end

    % Define urgency banner color styling
    switch reportData.predictedGrade
