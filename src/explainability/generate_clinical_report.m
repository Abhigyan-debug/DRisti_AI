function t = num3(v)
    if isnumeric(v) && isscalar(v) && isfinite(v), t = sprintf('%.3f', v); else, t = 'n/a'; end
end

function t = num2(v)
    if isnumeric(v) && isscalar(v) && isfinite(v), t = sprintf('%.1f', v); else, t = 'n/a'; end
end

function t = num4(v)
    if isnumeric(v) && isscalar(v) && isfinite(v), t = sprintf('%.4f', v); else, t = 'n/a'; end
end
