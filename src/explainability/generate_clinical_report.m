            badgeText = 'NO DIABETIC RETINOPATHY (ICDR GRADE 0)';
            actionColor = '#065f46';
        case 1
            badgeBg = '#f59e0b'; % Amber
            badgeText = 'MILD NPDR (ICDR GRADE 1) - NON-REFERABLE';
            actionColor = '#92400e';
        case 2
            badgeBg = '#ea580c'; % Orange
