function q = confidenceQualifier(reportData)
%CONFIDENCEQUALIFIER  Label the confidence honestly.
%
%   The report previously printed "(Platt Scaled)" unconditionally, while no
%   calibration existed anywhere in the codebase - a false label on a clinical
%   document. A calibrator now exists (models/calibrator.mat), but the report
%   must state which number it is actually showing.
%
%   It must also carry the domain caveat: the calibrator is fitted on APTOS,
%   and measured external validation shows the score distribution does not
%   transfer (sensitivity 90.3% internally, 31.2% on Messidor-2). A confidence
%   shown on an image from unseen equipment is not trustworthy.

    if ~isfield(reportData, 'predictedGrade') || ~isscalar(reportData.predictedGrade) || ...
            ~isfinite(reportData.predictedGrade)
        q = '(no grade produced - image rejected at the quality gate)';
    elseif isfield(reportData, 'calibrationApplied') && reportData.calibrationApplied
        q = '(Platt-calibrated on APTOS; not validated on other cameras)';
    else
        q = '(uncalibrated model output - not a probability)';
    end
end


function txt = lesionCell(value, fmt)
%LESIONCELL  Render a lesion statistic, or say why it is absent.
%
%   NaN means the detector behind this channel is not validated, so no number
%   is shown. Printing 0 there would be a clinical assertion - "we looked and
%   found none" - which is exactly what an unvalidated detector cannot support.
%
%   Measured per-lesion precision against IDRiD ground truth:
%       hard exudates 0.549 (reported; was 0.595, corrected - see
%       segmentExudates.m) | haemorrhages 0.034 | microaneurysms 0.021 |
%       soft exudates never measured.
%
%   A count at 2-3% precision on a clinical document is a fabricated finding
%   wearing an authoritative format.

    if isnan(value)
        txt = '<span style="font-size:13px; color:#94a3b8;">not validated</span>';
    else
        txt = sprintf(fmt, value);
    end
end


function t = asText(value, fmt)
%ASTEXT  Format a number for the report, or say it is absent.
%
%   Every value reaching the big SPRINTF must already be text. MATLAB's sprintf
%   flattens its arguments into one vector and recycles the format, so a char
%   array handed to a numeric specifier is expanded to ONE NUMBER PER CHARACTER
%   and silently consumes that many specifiers. When patientAge became the
%   string 'not recorded' against a %d, it ate twelve specifiers and every field
%   after it shifted - the disc coordinate ended up rendered as a lesion count.
%   Formatting here, and using %s throughout, makes that failure impossible.

    if isempty(value) || (isnumeric(value) && ~isfinite(value))
        t = 'not recorded';
    elseif ischar(value) || isstring(value)
        t = char(value);
    else
        t = sprintf(fmt, value);
    end
end


function t = ageText(value)
    if isnumeric(value) && isscalar(value) && isfinite(value)
        t = sprintf('%dY', round(value));
        return
    end

    t = asText(value, '%s');

    % An age typed into the web form arrives as TEXT, so "52" would print bare
    % while a numeric 52 prints "52Y" - the same field rendering two ways
    % depending on which caller filled it. Normalise only a plain integer:
    % "not recorded", "unknown" and anything else must pass through untouched
    % rather than acquire a spurious unit.
    if ~isempty(regexp(t, '^\s*\d{1,3}\s*$', 'once'))
        t = [strtrim(t) 'Y'];
    end
end


function t = pointText(pt)
%POINTTEXT  Pixel coordinates, or a statement that they were not found.
    if numel(pt) ~= 2 || any(~isfinite(pt))
        t = 'not located';
    else
        t = sprintf('[%d, %d]', round(pt(1)), round(pt(2)));
    end
end


function t = qualityDetail(reportData)
%QUALITYDETAIL  The quality number, named for what it actually is.
%
%   The template printed '(Score: 0.88)', implying a normalised [0,1] focus
%   score. The pipeline has no such score: it measures Laplacian variance on a
%   resolution-normalised image, which is unbounded and not a probability.
%   Printing it under a 0-1 label would misrepresent the metric, so it is
%   labelled as sharpness and omitted entirely when unavailable.

    if ~isfield(reportData, 'sharpness') || isempty(reportData.sharpness) || ...
            ~isfinite(reportData.sharpness)
        t = '';
        return
    end
    t = sprintf(' (sharpness %.0f', reportData.sharpness);
    if isfield(reportData, 'sharpnessBand') && ~isempty(reportData.sharpnessBand)
        t = [t ', ' char(reportData.sharpnessBand) ' band'];
    end
    t = [t ')'];
end

function h = embedOverlay(fundusImg, gradcamMap)
%EMBEDOVERLAY  Inline the fundus/Grad-CAM composite as a base64 data URI.
%
%   The report has to be one self-contained file. A screening report that
%   references an image on the local disk arrives at the district hospital as a
%   broken image icon, so the pixels travel inside the HTML.
%
%   Downscaled to 520px on the long side: the reviewer is confirming WHERE the
%   model looked, not counting microaneurysms, and a 4288px IDRiD frame would
%   add ~4 MB of base64 to a document that must open quickly over a rural link.

    if isempty(fundusImg)
        h = ['<div style="text-align:center; padding:20px; color:#94a3b8;">' ...
             '<b>No image supplied</b><br><span style="font-size:11px;">' ...
             'Grad-CAM localisation cannot be verified from this report.</span></div>'];
        return
    end

    img = fundusImg;
    if ~isempty(gradcamMap) && isequal(size(gradcamMap,1:2), size(img,1:2))
        img = compositeOverlay(img, gradcamMap);
    end

    scale = 520 / max(size(img,1), size(img,2));
    if scale < 1, img = imresize(img, scale); end
    if ~isa(img, 'uint8'), img = im2uint8(img); end

    tmp = [tempname '.png'];
    imwrite(img, tmp);
    fid = fopen(tmp, 'r');
    bytes = fread(fid, Inf, '*uint8');
    fclose(fid);
    delete(tmp);

    h = sprintf(['<img src="data:image/png;base64,%s" ' ...
                 'style="max-width:100%%; max-height:100%%; object-fit:contain;" ' ...
                 'alt="Fundus image with Grad-CAM overlay">'], ...
                matlab.net.base64encode(bytes));
end


function t = modelLabel(reportData)
    if isfield(reportData,'modelDescription') && ~isempty(reportData.modelDescription)
        t = char(reportData.modelDescription);
    else
        t = 'model not identified';
    end
end


function h = validationTableHtml(rd)
%VALIDATIONTABLEHTML  Every lesion channel, passed or failed, with its numbers.
%
%   Failures are shown, not omitted. A report listing only the channel that
%   worked implies the others were never tried, which overstates the system by
%   omission - and the fact that three of four detectors are unfit to display is
%   one of the more important things this document can tell a reviewer.

    h = '';
    if ~isfield(rd, 'detectorValidation') || isempty(rd.detectorValidation)
        return
    end
    rows = rd.detectorValidation;

    body = '';
    for i = 1:size(rows, 1)
        name = rows{i,1}; p = rows{i,2}; r = rows{i,3}; f1 = rows{i,4};
        verdict = rows{i,5};
        passed = startsWith(verdict, 'VALIDATED');
        if passed
            tag = ['<span style="background:#dcfce7;color:#14532d;padding:2px 6px;' ...
                   'border-radius:4px;font-size:10px;font-weight:bold;">DISPLAYED</span>'];
            rowStyle = 'color:#1f2937;';
        else
            tag = ['<span style="background:#f3f4f6;color:#6b7280;padding:2px 6px;' ...
                   'border-radius:4px;font-size:10px;font-weight:bold;">NOT VALIDATED</span>'];
            rowStyle = 'color:#9ca3af;';
        end
        body = [body sprintf([ ...
            '<tr style="border-bottom:1px solid #e5e7eb;font-size:11px;%s">' ...
            '<td style="padding:6px;font-weight:600;">%s</td>' ...
            '<td style="padding:6px;text-align:center;">%s</td>' ...
            '<td style="padding:6px;text-align:center;">%s</td>' ...
